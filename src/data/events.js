export const events = bairros.flatMap((bairro, bairroIndex) =>
  modelos.map((modelo, modeloIndex) => {
    const nivelRisco = Math.min(5, Math.max(1, modelo.risco + bairro.ajusteRisco - (modeloIndex % 4 === 0 ? 1 : 0)));
    const dificuldade = Math.min(92, modelo.dificuldade + bairro.ajusteRisco * 3 + (bairroIndex % 3) * 2 + (modeloIndex % 5));

    return {
      id: `evt-${String(bairroIndex + 1).padStart(2, "0")}-${String(modeloIndex + 1).padStart(2, "0")}`,
      titulo: `${modelo.titulo} em ${bairro.nome}`,
      descricao: `${modelo.descricao} A ocorrência acontece em ${bairro.nome}, ${bairro.nota}, e exige uma resposta coordenada antes que o risco vire ${riscoNome[nivelRisco - 1]}.`,
      bairro: bairro.nome,
      nivelRisco,
      dificuldade,
      requisitosPrincipais: modelo.requisitos,
      tags: [...modelo.tags, bairro.nome.toLowerCase().replaceAll(" ", "-")],
      limiteTempoNarrativo: modelo.tempo,
    };
  }),
);

export const eventCount = events.length;
